export const cssVariable = (token: PaletteToken) =>
  `--cg-${token.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`)}`;

export const palette = Object.fromEntries(
  Object.keys(light).map((token) => [
    token,
    `var(${cssVariable(token as PaletteToken)})`,
  ]),
) as Record<PaletteToken, string>;
